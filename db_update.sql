
CREATE TABLE Bookings (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    UserId INT NOT NULL FOREIGN KEY REFERENCES Users(Id),
    ShowId INT NOT NULL FOREIGN KEY REFERENCES Shows(Id),
    BookingDate DATETIME2 NOT NULL DEFAULT GETUTCDATE(),
    BookingType NVARCHAR(50) NOT NULL,
    TotalAmount DECIMAL(18,2) NOT NULL,
    Status NVARCHAR(50) NOT NULL
);

CREATE TABLE BookingSeats (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    BookingId INT NOT NULL FOREIGN KEY REFERENCES Bookings(Id),
    ScreenSeatId INT NOT NULL FOREIGN KEY REFERENCES ScreenSeats(Id),
    Price DECIMAL(18,2) NOT NULL
);

CREATE TABLE ActivityLogs (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    TheaterAdminId INT NOT NULL FOREIGN KEY REFERENCES Users(Id),
    ActionType NVARCHAR(50) NOT NULL,
    ActionDescription NVARCHAR(255) NOT NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETUTCDATE()
);

